"""
kg_query.py - query and export the plant knowledge graph.

Pattern queries (one hop, Cypher-like):
    (a:instrument)-[TRIPS]->(b:valve)
    (a)-[INSTALLED_ON]->(b:line) WHERE b.service = SG
    (a:equipment)-[FEEDS]->(b) WHERE a.area = 400
  a / b may carry a kind (equipment, line, valve, instrument, motor); the relation may be omitted: (a:valve)-[]->(b).
Graph queries: neighbours within n hops, shortest path between two items.
Exports: Cypher script for Neo4j (MERGE nodes and relationships), GraphML, nodes / edges CSV.
"""
import re

import networkx as nx
import pandas as pd

PATTERN = re.compile(r"^\s*\((\w+)(?::(\w+))?\)\s*-\s*\[\s*(\w*)\s*\]\s*->\s*\((\w+)(?::(\w+))?\)\s*(?:WHERE\s+(\w+)\.(\w+)\s*(=|!=|>|<|>=|<=|CONTAINS)\s*(.+))?\s*$", re.I)


def graph(nodes, triples):
    G = nx.MultiDiGraph()
    for r in nodes.to_dict("records"):
        G.add_node(r["id"], **{k: v for k, v in r.items() if k != "id" and pd.notna(v)})
    for s, r, o in triples[["subject", "relation", "object"]].itertuples(index=False):
        G.add_edge(s, o, relation=r)
    return G


def run(pattern, nodes, triples):
    """Run a one-hop pattern query. Returns a DataFrame of matches, or raises ValueError with a hint."""
    m = PATTERN.match(pattern or "")
    if not m:
        raise ValueError("Pattern not understood. Example: (a:instrument)-[TRIPS]->(b:valve)  or  (a)-[INSTALLED_ON]->(b:line) WHERE b.service = SG")
    va, ka, rel, vb, kb, wv, wp, op, wval = m.groups()
    N = nodes.set_index("id")
    t = triples.copy()
    if rel:
        t = t[t.relation.str.upper() == rel.upper()]
    kind = lambda ids: N.reindex(ids)["kind"].values
    if ka:
        t = t[kind(t.subject) == ka.lower()]
    if kb:
        t = t[kind(t.object) == kb.lower()]
    if wv:
        col = t.subject if wv == va else t.object
        if wp.lower() == "id":
            vals = col.values
        else:
            vals = N.reindex(col)[wp].values if wp in N.columns else [None] * len(col)
        w = wval.strip().strip("'\"")
        def test(x):
            if x is None or (isinstance(x, float) and pd.isna(x)):
                return False
            try:
                xf, wf = float(x), float(w)
                return {"=": xf == wf, "!=": xf != wf, ">": xf > wf, "<": xf < wf, ">=": xf >= wf, "<=": xf <= wf}.get(op.upper(), False)
            except ValueError:
                xs = str(x).lower()
                return {"=": xs == w.lower(), "!=": xs != w.lower(), "CONTAINS": w.lower() in xs}.get(op.upper(), False)
        t = t[[test(x) for x in vals]]
    out = pd.DataFrame({va: t.subject.values, "relation": t.relation.values, vb: t.object.values})
    out[f"{va} label"] = N.reindex(t.subject)["label"].values
    out[f"{vb} label"] = N.reindex(t.object)["label"].values
    return out


def neighbours(G, tag, hops=1):
    U = G.to_undirected(as_view=True)
    d = nx.single_source_shortest_path_length(U, tag, cutoff=hops)
    return pd.DataFrame([dict(id=n, hops=h, kind=G.nodes[n].get("kind"), label=G.nodes[n].get("label")) for n, h in sorted(d.items(), key=lambda x: x[1]) if n != tag])


def path(G, a, b, directed=True):
    H = G if directed else G.to_undirected(as_view=True)
    p = nx.shortest_path(H, a, b)
    steps = []
    for u, v in zip(p, p[1:]):
        rel = next(iter(G.get_edge_data(u, v).values()))["relation"] if G.has_edge(u, v) else next(iter(G.get_edge_data(v, u).values()))["relation"] + " (reverse)"
        steps.append(dict(step=len(steps) + 1, **{"from": u}, relation=rel, to=v))
    return pd.DataFrame(steps)


def to_cypher(nodes, triples):
    """Neo4j script: one MERGE per node (label = kind) and per relationship. Run it in Neo4j Browser or cypher-shell."""
    q = lambda s: "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"
    lines = ["// Plant knowledge graph - generated by pfd2pid", "// Run in Neo4j Browser or: cypher-shell -f plant.cypher", ""]
    for r in nodes.to_dict("records"):
        props = ", ".join(f"{k}: {q(v)}" for k, v in r.items() if k not in ("id", "x", "y") and pd.notna(v) and str(v) != "")
        label = str(r.get("kind", "item")).capitalize()
        lines.append(f"MERGE (n:{label} {{id: {q(r['id'])}}}) SET n += {{{props}}};")
    lines.append("")
    for s, r, o in triples[["subject", "relation", "object"]].itertuples(index=False):
        lines.append(f"MATCH (a {{id: {q(s)}}}), (b {{id: {q(o)}}}) MERGE (a)-[:{r}]->(b);")
    return "\n".join(lines) + "\n"
