"""
make_dataset.py - synthetic PFD -> P&ID dataset, generated by varying the gasifier-mode model.

Each sample pairs a PFD (equipment + streams, no valves or instruments) with the P&ID the rule generator
produces for it (lines, valves, instruments, relations). Variations: plant capacity, oxidant case, oxidant
pressure, syngas temperature, and five topology options.

IMPORTANT: every label comes from the rules in pfd_to_pid.py. A model trained on this learns those rules,
nothing more. Use it to test a training pipeline or to pre-train; real reviewed P&IDs are needed for real skill.

Run:  python make_dataset.py --n 5000 --out dataset
"""
import argparse
import json
import random
from pathlib import Path

import pandas as pd

import pfd_to_pid as p

HERE = Path(__file__).parent
# oxidant cases from the HMBD sheet: name -> (service code, diluent kg per 106 kg O2)
OXIDANT = {"air-blown": ("AIR", 350.0), "oxy-blown": ("OX", 11.0), "O2-CO2 45-55": ("OXC", 130.0),
           "O2-CO2 30-70": ("OXC", 247.33), "O2-CO2 21-79": ("OXC", 398.76)}
CLEANING = ["vendor package", "cooler + bag filter + condensing cooler + demister + blower", "cooler + bag filter + blower"]


def variant(rng, eq_all, base):
    """Return (params, equipment df, streams df) for one random plant variant."""
    scale = round(rng.uniform(0.3, 3.0), 3)                       # 0.3x .. 3x of 354 kg/h
    ox_name = rng.choice(list(OXIDANT))
    ox_service, diluent = OXIDANT[ox_name]
    cleaning = rng.choice(CLEANING)
    shots = rng.random() < 0.7                                     # heat-carrier (steel shot) loop present
    preheater = rng.random() < 0.75                                # oxidant pre-heater present
    engine = rng.random() < 0.8                                    # gas engine, else flare
    ox_press = round(rng.uniform(3, 8), 1)
    sg_temp = int(rng.uniform(400, 520))

    feed = 354 * scale
    oxid = (106 + diluent) * scale
    gas, char, ash = 212 * scale, 142 * scale, 6 * scale
    syngas = gas + char + oxid - ash

    st = base.copy()
    for no in ("0", "1", "2"):
        st.loc[st.no == no, "flow_kgh"] = round(feed, 1)
    st.loc[st.no == "13", "flow_kgh"] = round(gas, 1)
    st.loc[st.no == "14", "flow_kgh"] = round(char, 1)
    st.loc[st.no == "A1", "flow_kgh"] = round(ash, 1)
    for no in ("15", "16"):
        st.loc[st.no == no, ["flow_kgh", "press_bar", "service"]] = [round(oxid, 1), ox_press, ox_service]
    for no in ("17", "17A", "17B"):
        st.loc[st.no == no, "flow_kgh"] = round(syngas, 1)
    st.loc[st.no == "17", "temp_C"] = sg_temp

    drop = set()
    if not shots:                                                  # directly heated auger: no shot loop
        drop |= {"3", "9", "10", "12"}
    if not preheater:                                              # oxidant straight to gasifier
        drop |= {"15", "19", "19A"}
        st.loc[st.no == "16", ["from", "temp_C", "pid_hints"]] = ["PK-401", 40, "ISO;PCV;FIC;XV;CHK"]
    if cleaning == CLEANING[0]:                                    # single vendor package
        drop |= {"17A", "D1", "N2", "17B", "C1", "17C", "17D", "CWS1", "CWS2", "CWR1", "CWR2"}
        st.loc[st.no == "17", "to"] = "PK-402"
        st.loc[st.no == "18", ["from", "pid_hints"]] = ["PK-402", "ISO;XV"]
    elif cleaning == CLEANING[2]:                                  # no condensing cooler / demister
        drop |= {"C1", "17C", "CWS2", "CWR2"}
        st.loc[st.no == "17B", "to"] = "B-401"
        drop |= {"17D"}
    if not engine:                                                 # syngas to flare
        st.loc[st.no == "18", ["to", "pid_hints"]] = ["FL-201", "CHK;PCV;FA"]
        if preheater:                                              # no engine exhaust: pre-heater heat source is then undefined
            drop |= {"19", "19A"}
    st = st[~st.no.isin(drop)].reset_index(drop=True)
    params = dict(capacity_kgh=round(feed, 1), capacity_tpd=round(feed * 24 / 1000, 2), oxidant=ox_name, oxidant_pressure_bar=ox_press,
                  syngas_temp_C=sg_temp, cleaning=cleaning, shot_loop=shots, oxidant_preheater=preheater, end_use="engine" if engine else "flare")
    return params, eq_all, st


def to_sample(i, params, eq_all, st):
    G, eq, lines, inst, valves = p.build_frames(eq_all, st)
    clean = lambda df: json.loads(df.to_json(orient="records"))
    pfd_streams = st.drop(columns=["pid_hints", "description"])
    rel = []
    for a, b, d in G.edges(data=True):
        if "tap" in a or "tap" in b:
            continue
        if d["kind"] != "process":
            rel.append([a, "TRIPS" if d["kind"] == "trip" else "SIGNAL", b])
    pfd_text = "; ".join(f"{r['from']}->{r.to} [{r.service},{r.phase}" + (f",{r.flow_kgh:g}kg/h" if pd.notna(r.flow_kgh) else "") + "]"
                         for _, r in pfd_streams.iterrows())
    pid_text = ("LINES: " + ", ".join(lines.line_no) + " | VALVES: " + ", ".join(f"{v.tag}@{v.line}" for v in valves.itertuples())
                + " | INSTRUMENTS: " + ", ".join(f"{t.tag}@{t.attached_to}" for t in inst.itertuples())
                + " | SIGNALS: " + ", ".join(f"{a}>{b}" for a, _, b in rel))
    return dict(id=f"gasif-{i:06d}", params=params,
                pfd=dict(equipment=clean(eq[["tag", "name", "type", "area"]]), streams=clean(pfd_streams)),
                pid=dict(lines=clean(lines[["line_no", "pfd_stream", "from", "to", "size"]]), valves=clean(valves),
                         instruments=clean(inst), relations=rel),
                pfd_text=pfd_text, pid_text=pid_text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=5000)
    ap.add_argument("--out", default="dataset")
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    out = HERE / a.out
    out.mkdir(exist_ok=True)
    eq_all = pd.read_csv(p.DATA / "equipment.csv")
    base = pd.read_csv(p.DATA / "streams_gasifier_full.csv", dtype={"no": str})
    files = {k: open(out / f"{k}.jsonl", "w", encoding="utf-8") for k in ("train", "val", "test")}
    stats, summary = {"train": 0, "val": 0, "test": 0}, []
    for i in range(a.n):
        params, eq, st = variant(rng, eq_all, base)
        s = to_sample(i, params, eq, st)
        split = "train" if i % 10 < 8 else ("val" if i % 10 == 8 else "test")
        files[split].write(json.dumps(s) + "\n")
        stats[split] += 1
        summary.append(dict(id=s["id"], split=split, **params, n_equipment=len(s["pfd"]["equipment"]), n_streams=len(s["pfd"]["streams"]),
                            n_lines=len(s["pid"]["lines"]), n_valves=len(s["pid"]["valves"]), n_instruments=len(s["pid"]["instruments"])))
    for f in files.values():
        f.close()
    df = pd.DataFrame(summary)
    df.to_csv(out / "summary.csv", index=False)
    topo = df[["oxidant", "cleaning", "shot_loop", "oxidant_preheater", "end_use"]].drop_duplicates().shape[0]
    print(stats, "| distinct topology/oxidant combinations:", topo)


if __name__ == "__main__":
    main()
